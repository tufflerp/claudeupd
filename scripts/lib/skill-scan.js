'use strict';

/**
 * Static safety scanner for skill folders (Node side).
 *
 * Every file in a skill is checked against the shared rules in
 * skill-scan-core.js for malware-like behaviour: remote code execution,
 * credential theft, data exfiltration, obfuscated payloads, destructive
 * commands, persistence, hidden Unicode and prompt injection. Findings are
 * either `block` (the skill must not be imported or shipped) or `warn`
 * (allowed, but reported for human review).
 *
 * Markdown files are documentation, so code-shaped rules only warn there;
 * the same patterns in executable files block. Hidden Unicode and prompt
 * injection block everywhere because they target the model, not the shell.
 */

const crypto = require('crypto');
const fs = require('fs');
const path = require('path');
const { MAX_SKILL_BYTES, RULES, classifyFile, hasBinaryMagic, scanText } = require('./skill-scan-core');

// Interpreter caches are git-ignored build output, regenerated by running tests.
const CACHE_DIRS = new Set(['__pycache__', '.pytest_cache', '.mypy_cache']);

function walk(dir, base, acc, options) {
  for (const entry of fs.readdirSync(dir, { withFileTypes: true })) {
    const full = path.join(dir, entry.name);
    const rel = path.relative(base, full);
    if (entry.isSymbolicLink()) {
      acc.push({ rel, full, symlink: true });
    } else if (entry.isDirectory()) {
      if (options.ignoreCaches && CACHE_DIRS.has(entry.name)) continue;
      if (entry.name === 'node_modules' || entry.name === '.git') {
        acc.push({ rel, full, vendored: true });
        continue;
      }
      walk(full, base, acc, options);
    } else if (entry.isFile()) {
      acc.push({ rel, full });
    }
  }
  return acc;
}

/**
 * Scan an entire skill folder.
 *
 * @param {string} skillDir - Absolute path to the skill folder
 * @param {{ ignoreCaches?: boolean }} [options] - ignoreCaches skips git-ignored
 *   interpreter caches; use it only for the repository's own working tree
 * @returns {{ name: string, files: number, bytes: number, findings: Array<object>, blocked: boolean }}
 */
function scanSkill(skillDir, options = {}) {
  const name = path.basename(skillDir);
  const findings = [];
  let bytes = 0;
  const files = walk(skillDir, skillDir, [], options);

  const add = (severity, rule, file, message) => findings.push({ severity, rule, file, line: 0, message });

  if (!fs.existsSync(path.join(skillDir, 'SKILL.md'))) {
    add('block', 'missing-skill-md', '.', 'Folder has no SKILL.md');
  }

  for (const file of files) {
    if (file.symlink) {
      add('block', 'symlink', file.rel, 'Symbolic link could point outside the skill folder');
      continue;
    }
    if (file.vendored) {
      add('block', 'vendored-directory', file.rel, 'Bundled node_modules or .git directory');
      continue;
    }

    const stat = fs.statSync(file.full);
    bytes += stat.size;

    const decision = classifyFile(file.rel, stat.size);
    if (decision.action === 'finding' && decision.finding.severity === 'block') {
      findings.push(decision.finding);
      continue;
    }

    // Check the header before trusting the extension: a renamed .exe is still an .exe.
    const buffer = fs.readFileSync(file.full);
    if (hasBinaryMagic(buffer)) {
      add('block', 'executable-binary', file.rel, 'File contents are a native executable');
      continue;
    }
    if (decision.action === 'finding') {
      findings.push(decision.finding);
      continue;
    }
    if (decision.action === 'skip') continue;

    findings.push(...scanText(file.rel, buffer.toString('utf8')));
  }

  if (bytes > MAX_SKILL_BYTES) {
    add('block', 'oversized-skill', '.', `Skill is larger than ${MAX_SKILL_BYTES / 1024 / 1024} MB`);
  }

  return {
    name,
    files: files.length,
    bytes,
    findings,
    blocked: findings.some((f) => f.severity === 'block'),
  };
}

/**
 * Scan every skill folder inside a directory.
 *
 * @param {string} skillsDir
 * @param {{ ignoreCaches?: boolean }} [options]
 * @returns {Array<ReturnType<typeof scanSkill>>}
 */
function scanSkillsDir(skillsDir, options = {}) {
  return fs.readdirSync(skillsDir, { withFileTypes: true })
    .filter((entry) => entry.isDirectory())
    .map((entry) => scanSkill(path.join(skillsDir, entry.name), options))
    .sort((a, b) => a.name.localeCompare(b.name));
}

function sha256File(file) {
  return crypto.createHash('sha256').update(fs.readFileSync(file)).digest('hex');
}

/**
 * Load the reviewed-exceptions list. Missing file means no exceptions.
 *
 * @param {string} file
 * @returns {Array<{ skill: string, file: string, rule: string, sha256: string, reason: string }>}
 */
function loadAllowlist(file) {
  if (!fs.existsSync(file)) return [];
  const parsed = JSON.parse(fs.readFileSync(file, 'utf8'));
  return Array.isArray(parsed.entries) ? parsed.entries : [];
}

/**
 * Mark findings covered by a reviewed exception as allowed. An exception only
 * applies while the file's sha256 matches, so edited files are re-flagged.
 *
 * @param {ReturnType<typeof scanSkill>} result
 * @param {string} skillDir
 * @param {ReturnType<typeof loadAllowlist>} entries
 * @returns {ReturnType<typeof scanSkill>}
 */
function applyAllowlist(result, skillDir, entries) {
  const hashes = new Map();
  const hashOf = (rel) => {
    if (!hashes.has(rel)) {
      const full = path.join(skillDir, rel);
      hashes.set(rel, fs.existsSync(full) ? sha256File(full) : null);
    }
    return hashes.get(rel);
  };

  const findings = result.findings.map((finding) => {
    if (finding.severity !== 'block') return finding;
    const rel = finding.file.split(path.sep).join('/');
    const entry = entries.find((e) => e.skill === result.name && e.file === rel && e.rule === finding.rule);
    if (entry && entry.sha256 === hashOf(finding.file)) {
      return { ...finding, severity: 'allowed', reason: entry.reason };
    }
    return finding;
  });

  return { ...result, findings, blocked: findings.some((f) => f.severity === 'block') };
}

module.exports = {
  RULES,
  scanText,
  scanSkill,
  scanSkillsDir,
  loadAllowlist,
  applyAllowlist,
  sha256File,
};
